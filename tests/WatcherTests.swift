// Watcher（クリップボードの読み取り）のテスト。専用の名前のクリップボードを使う
import AppKit

func watcherTests() {
    let pb = NSPasteboard(name: .init("com.guribow.cliphistory.test.watcher"))
    defer { pb.releaseGlobally() }
    func put(_ pairs: [(NSPasteboard.PasteboardType, Data)]) {
        pb.declareTypes(pairs.map(\.0), owner: nil)
        for (type, data) in pairs { pb.setData(data, forType: type) }
    }
    let hello = Data("こんにちは".utf8)

    put([(.string, hello)])
    if case .text(let s)? = Watcher.read(pb) { check(s == "こんにちは", "テキストを読む") } else { check(false, "テキストを読む") }

    put([(.string, Data(" \n\t".utf8))])
    check(Watcher.read(pb) == nil, "空白だけのテキストは読まない")

    put([(.string, hello), (.init("org.nspasteboard.ConcealedType"), Data())])
    check(Watcher.read(pb) == nil, "ConcealedType の印があれば読まない")
    put([(.string, hello), (.init("org.nspasteboard.TransientType"), Data())])
    check(Watcher.read(pb) == nil, "TransientType の印があれば読まない")
    put([(.string, hello), (.init("org.nspasteboard.AutoGeneratedType"), Data())])
    check(Watcher.read(pb) == nil, "AutoGeneratedType の印があれば読まない")

    put([(.string, Data("a.txt".utf8)), (.fileURL, Data("file:///tmp/a.txt".utf8))])
    check(Watcher.read(pb) == nil, "Finder でコピーしたファイルは読まない")

    let rep = testImage(3, 2)
    let png = rep.representation(using: .png, properties: [:])!
    put([(.png, png)])
    if case .image(let d, let w, let h)? = Watcher.read(pb) {
        check(d == png && w == 3 && h == 2, "PNG をそのまま読む")
    } else { check(false, "PNG をそのまま読む") }

    let tiff = rep.tiffRepresentation!
    var first: Data?
    put([(.tiff, tiff)])
    if case .image(let d, let w, let h)? = Watcher.read(pb) {
        check(d.starts(with: [0x89, 0x50, 0x4E, 0x47]) && w == 3 && h == 2, "TIFF は PNG に変えて読む")
        first = d
    } else { check(false, "TIFF は PNG に変えて読む") }
    put([(.tiff, tiff)])
    if case .image(let d, _, _)? = Watcher.read(pb) {
        check(d == first, "同じ TIFF は毎回同じ PNG になる（重複を見分けられる）")
    } else { check(false, "同じ TIFF は毎回同じ PNG になる（重複を見分けられる）") }

    put([(.string, hello), (.png, png)])
    if case .text? = Watcher.read(pb) { check(true, "テキストと画像があればテキストを読む") }
    else { check(false, "テキストと画像があればテキストを読む") }

    put([(.png, Data(count: Watcher.maxImageBytes + 1))])
    check(Watcher.read(pb) == nil, "50 MB を超える画像は読まない")
    // 大きな写真（JPEG）は、TIFF に直した大きさではなく元の大きさで測る
    let photo = testImage(5000, 4000)   // TIFF にすると約 80 MB、JPEG なら小さい
    let jpeg = photo.representation(using: .jpeg, properties: [:])!
    put([(.init("public.jpeg"), jpeg)])
    if case .image(_, let w, let h)? = Watcher.read(pb) {
        check(w == 5000 && h == 4000, "大きな写真（JPEG）も画像として読む")
    } else { check(false, "大きな写真（JPEG）も画像として読む") }

    put([(.string, Data(String(repeating: "a", count: Watcher.maxTextBytes + 1).utf8))])
    check(Watcher.read(pb) == nil, "とても長いテキストは読まない")
    put([(.string, Data(String(repeating: "a", count: Watcher.maxTextBytes).utf8))])
    check(Watcher.read(pb) != nil, "上限ちょうどのテキストは読む")

    put([(.png, Data([1, 2, 3]))])
    check(Watcher.read(pb) == nil, "画像として読めないものは読まない")

    // check() と一時停止
    let store = Store(dir: tempDir(), limit: 200)
    let w = Watcher(store: store, pasteboard: pb)
    put([(.string, Data("one".utf8))])
    w.check()
    check(store.items.map(\.text) == ["one"], "変わったら取り込む")
    w.check()
    check(store.items.count == 1, "変わっていなければ何もしない")
    w.paused = true
    put([(.string, Data("two".utf8))])
    w.check()
    w.paused = false
    w.check()
    check(store.items.map(\.text) == ["one"], "一時停止中のものは、再開しても取り込まない")
    put([(.string, Data("three".utf8))])
    w.check()
    check(store.items.map(\.text) == ["three", "one"], "再開したあとのものは取り込む")
    put([(.string, Data("four".utf8))])
    w.skipCurrent()
    w.check()
    check(store.items.count == 2, "skipCurrent のあとは今の中身を読まない")
}
